  /** La traduction d'un texte français, ou le texte lui-même s'il n'y en a pas. */
  function tr(texte) {
    if (LANGUE === "fr" || typeof texte !== "string") return texte;
    const cle = texte.replace(/\s+/g, " ").trim();
    if (!cle) return texte;
    let resultat = DICO[cle];
    if (resultat === undefined) {
      // « expérience » -> on cherche « Expérience », et on rend la traduction en minuscule.
      const majuscule = cle[0].toUpperCase() + cle.slice(1);
      if (majuscule !== cle && DICO[majuscule] !== undefined) resultat = DICO[majuscule][0].toLowerCase() + DICO[majuscule].slice(1);
    }
    if (resultat === undefined) {
      for (const [motif, modele] of MOTIFS) {
        const m = cle.match(motif);
        if (m) { resultat = modele.replace(/\$(t?)(\d)/g, (_, traduit, n) => (traduit ? tr(m[n]) : m[n])); break; }
      }
    }
    if (resultat === undefined) return texte;
    // On garde les espaces qui entouraient le texte d'origine.
    return texte.match(/^\s*/)[0] + resultat + texte.match(/\s*$/)[0];
  }
  window.tr = tr;

