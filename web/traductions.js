  // ---------- Traduction de la page, puis de tout ce qui y est ajouté ----------
  const ATTRIBUTS = ["placeholder", "title", "aria-label", "alt"];
  const IGNORES = new Set(["SCRIPT", "STYLE", "TEXTAREA"]);

  function traduireLien(a) {
    // Les liens internes restent dans la langue choisie : /creer -> /en/creer.
    const href = a.getAttribute("href");
    if (!href || !href.startsWith("/") || href.startsWith("//") || a.hasAttribute("hreflang")) return;
    if (/^\/(en|it)(\/|$|\?)/.test(href) || /^\/(api|exemple|img)\//.test(href) || /\.[a-z0-9]{2,4}($|\?)/i.test(href)) return;
    a.setAttribute("href", window.PREFIXE_SITE + href);
  }

  function traduireElement(el) {
    for (const attribut of ATTRIBUTS) {
      const valeur = el.getAttribute(attribut);
      if (valeur) { const t = tr(valeur); if (t !== valeur) el.setAttribute(attribut, t); }
    }
    if (el.tagName === "A") traduireLien(el);
  }

  function traduireTexte(noeud) {
    const parent = noeud.parentElement;
    if (!parent || IGNORES.has(parent.tagName) || parent.closest("[translate=no]")) return;
    const t = tr(noeud.nodeValue);
    if (t !== noeud.nodeValue) noeud.nodeValue = t;
  }

  function traduire(racine) {
    if (racine.nodeType === Node.TEXT_NODE) return traduireTexte(racine);
    if (racine.nodeType !== Node.ELEMENT_NODE || IGNORES.has(racine.tagName)) return;
    traduireElement(racine);
    for (const el of racine.querySelectorAll("*")) traduireElement(el);
    const textes = document.createTreeWalker(racine, NodeFilter.SHOW_TEXT);
    while (textes.nextNode()) traduireTexte(textes.currentNode);
  }

  document.title = tr(document.title);
  traduire(document.body);
  new MutationObserver(changements => {
    for (const c of changements) {
      if (c.type === "characterData") traduireTexte(c.target);
      else if (c.type === "attributes") traduireElement(c.target);
      else for (const noeud of c.addedNodes) traduire(noeud);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true,
                              attributes: true, attributeFilter: [...ATTRIBUTS, "href"] });

